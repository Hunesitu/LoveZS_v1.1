"""
数字炸弹 - 对手命中提示语

每当对手猜了一次，前端会弹出一条提示，顺带告诉玩家局面紧迫程度。
提示语只依赖「对手这次猜对了几个」，与具体数字无关，因此不会泄露任何秘密。

为了在轮询中保持稳定（同一手猜测每次取到同一句），提示语用猜测记录的 id 作为
随机种子；只有需要真正的随机推荐时才不传 seed。
"""

import random

HINTS_BY_HITS = {
    0: [
        '对方一个都没对，你的数字很安全',
        '对方还在摸黑，稳住优势',
        '这轮对方完全没中，抓紧机会',
        '对方离得还远，先手在你这边',
        '对方还在试探，你可以再快一点',
        '对方空手而归，别浪费这波优势',
    ],
    1: [
        '对方猜对 1 个，开始有感觉了',
        '对方摸到一位，要加快节奏',
        '1 个命中，对方正在找方向',
        '对方对了 1 个，别被慢慢磨出来',
        '对方打开了一个缺口，留意',
        '只对 1 个，形势还稳',
    ],
    2: [
        '对方猜对 2 个，追得有点紧了',
        '已经对了一半，得抢先一步',
        '对方中了两处，压力来了',
        '2 个命中，对方越来越近',
        '对方找到一半，别让节奏被带走',
        '对了一半，接下来是决胜阶段',
    ],
    3: [
        '对方只差 1 个就全中，快抢',
        '3 个命中，胜负就在下一手',
        '对方已经贴脸了，全力冲刺',
        '就剩最后一位，别犹豫',
        '3 个对了，现在拼的是手速',
        '危险，对方马上要猜穿',
    ],
}


def get_opponent_hint(hits, seed=None):
    """按对手命中数取一条提示语；4 个全中时不返回（对局已结束）。"""
    hints = HINTS_BY_HITS.get(hits)
    if not hints:
        return ''
    if seed is None:
        return random.choice(hints)
    return random.Random(seed).choice(hints)
